def insertion_sort(arr):
    key = 1
    lon_arr = len(arr)
    key = 1
    # arr_tem = [0]*lon_arr
    for i in range(lon_arr):
      for j in range(key):
        if arr[j] < arr[i]:
          temp = arr[i]
          arr[i] = arr[j]
          arr[j] = temp
      key += 1
    return arr

def aplanado_arreglo(matrix):
  # Aplanamos la matriz de valores
  y, x = matrix.shape
  arr = [0]*(y*x)
  for j in range(y):
    for i in range(x):
      arr[j * x + i] = matrix[j][i]
  return np.array(arr)

def mediana_artesanal(matrix):
  # Aplanamos la matriz de valores
  arr = aplanado_arreglo(matrix)
  # Los acomodamos
  arr = insertion_sort(arr)
  longitud = len(arr)
  # Obtenemos el índice donde está la mitad de datos (50%)
  temp = 0
  while temp < longitud/2:
    temp += 1
  return arr[int(temp)]

